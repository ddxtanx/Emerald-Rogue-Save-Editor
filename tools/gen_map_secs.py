#!/usr/bin/env python3
"""Regenerate src/map_secs.rs (met-location section names) from the game tree.

The met-location byte stores a region-map SECTION id, not a map id: the game
writes `GetCurrentRegionMapSectionId()` into it (src/pokemon.c:946-947) and
compares it to the current section (src/pokemon.c:3508). `include/constants/
region_map_sections.h` is therefore the authoritative id -> text table, and its
`MAPSEC_*` macro names are the game's own names for those sections.

Usage: tools/gen_map_secs.py [game-tree-root]
"""
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '/workspace/hermes/rogue-src'
path = f'{root}/include/constants/region_map_sections.h'
src = open(path, errors='ignore').read()

pairs = []
for m in re.finditer(r'^#define\s+((?:MAPSEC|METLOC)_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+)\s*$', src, re.M):
    name, val = m.group(1), int(m.group(2), 16)
    pairs.append((val, name))

assert len(pairs) >= 200, f'only parsed {len(pairs)} sections from {path}'
seen = {}
for val, name in pairs:
    assert val <= 0xFF, f'{name} = {val:#x} does not fit the u8 met-location byte'
    if val in seen:
        assert seen[val] == name, f'id {val:#x} claimed by {seen[val]} and {name}'
        continue
    seen[val] = name


def label(const):
    """MAPSEC_LAVARIDGE_TOWN -> 'Lavaridge Town'. The macro name IS the game's
    name for the section, so this is a relabel, not an invention."""
    words = re.sub(r'^(MAPSEC|METLOC)_', '', const).split('_')
    return ' '.join(w.capitalize() for w in words)


lines = [f'    ({val}, "{label(name)}"),' for val, name in sorted(seen.items())]
out = """// Auto-generated by tools/gen_map_secs.py from the v2.2.0-EX game tree
// (include/constants/region_map_sections.h). Do not edit by hand; regenerate
// with `tools/gen_map_secs.py [tree-root]`.
#![allow(dead_code)]

/// Met location ids are region-map SECTION ids: the game stores
/// `GetCurrentRegionMapSectionId()` in the byte (src/pokemon.c:946-947) and
/// compares it with the current section (src/pokemon.c:3508). The section name
/// is the description of the id, so the UI shows the name.
///
/// Id 0 is a real section (Pokemon Hub), not "unset" - unlike species/item/move
/// ids, this namespace must not treat 0 as empty. The three 0xF? entries are the
/// `METLOC_*` specials the game writes for eggs, in-game trades and the
/// Mirage Island-style fateful encounters.
pub const MAPSECS: &[(u16, &str)] = &[
""" + '\n'.join(lines) + "\n];\n"
open('src/map_secs.rs', 'w').write(out)
print(f'map_secs: {len(seen)} sections, ids {min(seen):#x}..{max(seen):#x}')
for probe in (0x00, 0x03, 0x10, 0xD5, 0xFD, 0xFF):
    print(f'  {probe:#04x} -> {label(seen[probe])}')
