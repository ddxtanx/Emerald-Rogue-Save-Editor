#!/usr/bin/env python3
"""Regenerate data/move_pp.csv (base PP per move id) from the game tree.

Provenance note: this table used to be generated from `rogue-src-2207`, whose
move table only reached id ~376. The v2.2.0-EX tree defines 957 moves
(include/constants/moves.h), so every Gen-4+ move id (e.g. Zen Headbutt = 428)
had no entry and the editor showed "PP 0/00". Generation is now against the
tree the saves were made with (`rogue-src`), and `move_pp_table_covers_the_moves_ui`
in save_tests.rs fails the build if a move the picker offers has no PP entry.

Usage: tools/gen_movepp.py [game-tree-root]
"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '/workspace/hermes/rogue-src'
moves_h = open(f'{root}/include/constants/moves.h', errors='ignore').read()
moves_c = open(f'{root}/src/data/battle_moves.h', errors='ignore').read()

name2id = {m.group(1): int(m.group(2))
           for m in re.finditer(r'#define\s+(MOVE_\w+)\s+(\d+)\s*$', moves_h, re.M)}

# Only the mainline table: that is the one indexed by the stored move id.
tbl = moves_c.split('const struct BattleMove gBattleMoves_')
main = [t for t in tbl if t.startswith('Mainline')]
assert len(main) == 1, f'expected exactly one mainline table, got {len(main)}'
main = main[0]

pp = {}
# Split on the designated-initializer KEYS rather than on closing braces: some
# entries hold nested braces (`[MOVE_STONE_AXE] =` even opens its brace on the
# next line), so a brace-matching pattern silently swallows the entry that
# follows and drops a move id from the table.
keys = [(m.start(), m.group(1)) for m in re.finditer(r'\[(MOVE_\w+)\]\s*=\s*', main)]
for i, (pos, name) in enumerate(keys):
    stop = keys[i + 1][0] if i + 1 < len(keys) else len(main)
    body = main[pos:stop]
    mm = re.search(r'\.pp\s*=\s*([\w ()|]+?),', body)
    if not mm:
        continue
    val = mm.group(1).strip()
    if not re.fullmatch(r'\d+', val):
        continue
    mid = name2id.get(name)
    if mid is None:
        continue
    pp[mid] = int(val)

# Anchors: POUND (35 PP) and, for the id range that used to be missing,
# Zen Headbutt = 428 with 15 PP.
assert name2id.get('MOVE_ZEN_HEADBUTT') == 428, name2id.get('MOVE_ZEN_HEADBUTT')
assert pp.get(name2id['MOVE_POUND']) == 35, pp.get(name2id['MOVE_POUND'])
assert pp.get(428) == 15, pp.get(428)

defined = sorted(v for v in name2id.values() if 0 < v < max(name2id.values()))
missing = [i for i in defined if i not in pp]
out = (
    f"# Generated by tools/gen_movepp.py from the game tree (source: {root}).\n"
    "# Do not edit by hand; regenerate. Base max PP per move id, exactly as the\n"
    "# game's own move table stores it (gBattleMoves_Mainline .pp field).\n"
    "move_id,base_pp\n"
    + "\n".join(f"{k},{v}" for k, v in sorted(pp.items()))
    + "\n"
)
data_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
os.makedirs(data_dir, exist_ok=True)
with open(os.path.join(data_dir, "move_pp.csv"), "w") as fh:
    fh.write(out)
print(f'data/move_pp.csv: {len(pp)} entries, max id {max(pp)}, defined ids {len(defined)}')
if missing:
    print('ids defined but with no .pp entry:', missing[:40], '...' if len(missing) > 40 else '')
