#!/usr/bin/env python3
"""Regenerate src/weather_names.rs from the game tree's weather constants.

`hubMap.weatherState` is NOT one of these ids (it is a u16 seed the game folds
through `% 5` / `% 6` per season), but every weather the game can show IS one,
so the constants are the authoritative id -> text table for the weather picker.
Macro aliases (WEATHER_PSYCHIC_FOG == WEATHER_FOG_HORIZONTAL) are kept so the
C code's own spelling can be mirrored.

Usage: tools/gen_weather_names.py [game-tree-root]
"""
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '/workspace/hermes/rogue-src'
path = f'{root}/include/constants/weather.h'
src = open(path, errors='ignore').read()

ids, aliases = {}, {}
for m in re.finditer(
        r'^#define\s+(WEATHER_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)(?:\s*/\*.*?\*/\s*//\s*(.*))?(?:\s*//\s*(.*))?$',
        src, re.M):
    name, val = m.group(1), int(m.group(2), 0)
    note = (m.group(3) or m.group(4) or '').strip()
    ids[name] = (val, note)

for m in re.finditer(r'^#define\s+(WEATHER_[A-Z0-9_]+)\s+(WEATHER_[A-Z0-9_]+)\s*$', src, re.M):
    if m.group(2) in ids:
        aliases[m.group(1)] = m.group(2)

assert ids.get('WEATHER_NONE') == (0, ''), ids.get('WEATHER_NONE')
assert ids['WEATHER_SANDSTORM'][0] == 8, ids.get('WEATHER_SANDSTORM')

# Trailing source comments that are short enough to be a label suffix; anything
# longer is prose about the engine and does not belong in a combobox row.
# `// Unused` is deliberately dropped: it records what *vanilla* pokeemerald does
# with the constant, and Rogue's winter hub weather uses WEATHER_SNOW, so the
# stale annotation would contradict the mapping the editor is showing.
def suffix(note):
    note = note.strip()
    if not note or note.lower() == 'unused':
        return ''
    if len(note) > 24 or note.startswith('These'):
        return ''
    return f' ({note[0].upper()}{note[1:]})'


def label(const):
    return ' '.join(w.capitalize() for w in const[len('WEATHER_'):].split('_')) + suffix(ids[const][1])


by_id = {}
for const, (val, _) in ids.items():
    by_id.setdefault(val, const)

entries = '\n'.join(f'    ({val}, "{label(const)}"),' for val, const in sorted(by_id.items()))
consts = '\n'.join(f'pub const {c}: u16 = {ids[c][0]};' for c in sorted(ids, key=lambda c: (ids[c][0], c)))
alias_consts = '\n'.join(f'pub const {a}: u16 = {ids[t][0]}; // == {t}' for a, t in sorted(aliases.items()))

out = f"""// Auto-generated by tools/gen_weather_names.py from the v2.2.0-EX game tree
// (include/constants/weather.h). Do not edit by hand; regenerate with
// `tools/gen_weather_names.py [tree-root]`.
#![allow(dead_code)]

/// The engine's weather ids (`WEATHER_*`), as the game names them. Names come
/// from the macro, and a short trailing comment from the header is kept as a
/// suffix where the header itself annotates the meaning (e.g. fog = terrain).
pub const WEATHER_NAMES: &[(u16, &str)] = &[
{entries}
];

{consts}

{alias_consts}

pub fn weather_name(id: u16) -> &'static str {{
    WEATHER_NAMES
        .iter()
        .find(|(v, _)| *v == id)
        .map(|(_, n)| *n)
        .unwrap_or("no such weather id in weather.h")
}}
"""
open('src/weather_names.rs', 'w').write(out)
print(f'weather_names: {len(by_id)} ids, {len(ids)} consts, {len(aliases)} aliases')
for probe in (0, 3, 5, 6, 9, 16):
    print(f'  {probe} -> {label(by_id[probe])}')
